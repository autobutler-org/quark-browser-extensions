export type MessageKey = keyof typeof messagePlaceholders;

// One string per placeholder, so a call with the wrong number of substitutions doesn't compile.
type Strings<P extends readonly string[]> = { -readonly [I in keyof P]: string };
type Substitutions<K extends MessageKey> = Strings<(typeof messagePlaceholders)[K]>;

const i18n = (): typeof chrome.i18n | undefined => (typeof chrome === "undefined" ? undefined : chrome.i18n);

// The key itself stands in for a message the browser can't find, so a missing one shows up instead of a blank.
export const t = <K extends MessageKey>(key: K, ...substitutions: Substitutions<K>): string => {
  const message = i18n()?.getMessage(key, [...substitutions]) ?? "";
  return message === "" ? key : message;
};

const locale = (): string | undefined => i18n()?.getUILanguage();

export const formatNumber = (value: number): string => new Intl.NumberFormat(locale()).format(value);

// "15 minutes", "15 min" or "15m", in the browser's language.
export const formatDuration = (value: number, unit: "second" | "minute", unitDisplay: "long" | "short" | "narrow"): string =>
  new Intl.NumberFormat(locale(), { style: "unit", unit, unitDisplay }).format(value);
